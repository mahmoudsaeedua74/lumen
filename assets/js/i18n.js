  function readLang() {
    try {
      var stored = localStorage.getItem(STORAGE_KEY);
      if (stored === "ar" || stored === "en") return stored;
    } catch (e) {}
    return DEFAULT_LANG;
  }

  var current = readLang();

  function t(key, vars) {
    var table = STRINGS[current] || STRINGS.ar;
    var value = table[key] || STRINGS.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach(function (k) {
        value = value.replace("{" + k + "}", String(vars[k]));
      });
    }
    return value;
  }

  function localized(value) {
    if (value == null) return "";
    if (typeof value === "string") return value;
    if (typeof value === "object") return value[current] || value.ar || value.en || "";
    return String(value);
  }

  function setLang(lang) {
    if (lang !== "ar" && lang !== "en") return;
    current = lang;
    try {
      localStorage.setItem(STORAGE_KEY, lang);
    } catch (e) {}
    applyDocumentLang();
    window.dispatchEvent(new CustomEvent("lumen:langchange", { detail: { lang: lang } }));
  }

  function applyDocumentLang() {
    var html = document.documentElement;
    html.lang = current === "ar" ? "ar-SA" : "en";
    html.dir = current === "ar" ? "rtl" : "ltr";
    html.classList.toggle("is-ar", current === "ar");
    html.classList.toggle("is-en", current === "en");
  }

  function applyI18nAttributes(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach(function (el) {
      var key = el.getAttribute("data-i18n");
      if (!key) return;
      el.textContent = t(key);
    });
    root.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-placeholder");
      if (!key) return;
      el.setAttribute("placeholder", t(key));
    });
    root.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
      var key = el.getAttribute("data-i18n-aria");
      if (!key) return;
      el.setAttribute("aria-label", t(key));
    });
  }

  applyDocumentLang();

  window.LumenI18n = {
    t: t,
    localized: localized,
    getLang: function () {
      return current;
    },
    setLang: setLang,
    toggleLang: function () {
      setLang(current === "ar" ? "en" : "ar");
    },
    apply: applyI18nAttributes,
    applyDocumentLang: applyDocumentLang,
  };
